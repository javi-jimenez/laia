#!/usr/bin/env python3
"""Generate the citation artifacts of the whitepapers.

Everything is derived from the YAML front matter of ``whitepapers/*.md`` plus an
optional DOI registry (``whitepapers/dois.json``, written by
``scripts/zenodo_publish.py``). Outputs:

  * ``CITATION.cff``              — GitHub "Cite this repository" and ORCID/Zenodo imports
  * ``whitepapers/references.bib`` — BibTeX for LaTeX, Zotero, Mendeley
  * ``whitepapers/metadata.json`` — machine-readable feed for the website

Usage:
    python3 scripts/whitepaper_citations.py            # write the files
    python3 scripts/whitepaper_citations.py --check    # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from whitepaper_meta import (
    REPO_ROOT,
    Paper,
    load_papers,
    numbered,
    split_name,
)

WHITEPAPERS_DIR = REPO_ROOT / "whitepapers"
DOI_FILE = WHITEPAPERS_DIR / "dois.json"
CFF_FILE = REPO_ROOT / "CITATION.cff"
BIB_FILE = WHITEPAPERS_DIR / "references.bib"
JSON_FILE = WHITEPAPERS_DIR / "metadata.json"

PROJECT_TITLE = "LAIA Whitepapers"


def load_dois() -> dict[str, dict[str, object]]:
    if not DOI_FILE.exists():
        return {}
    data = json.loads(DOI_FILE.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"error: {DOI_FILE.name} must contain an object keyed by slug")
    return data


def bib_key(paper: Paper) -> str:
    family = split_name(paper.authors[0])[0].split()[-1] if paper.authors else "laia"
    ascii_family = (
        family.lower()
        .replace("í", "i")
        .replace("é", "e")
        .replace("á", "a")
        .replace("ó", "o")
        .replace("ú", "u")
        .replace("ñ", "n")
    )
    return f"{ascii_family}{paper.year}{paper.slug.split('-')[0]}"


def render_bibtex(papers: list[tuple[int, Paper]], dois: dict) -> str:
    keys = [bib_key(paper) for _, paper in papers]
    duplicates = {key for key in keys if keys.count(key) > 1}
    if duplicates:
        raise SystemExit(
            "error: duplicate BibTeX keys: "
            + ", ".join(sorted(duplicates))
            + " (add a distinct `order` or rename a slug)"
        )

    blocks = [
        "% Generated by scripts/whitepaper_citations.py — do not edit by hand.",
        "% Source: whitepapers/*.md front matter + whitepapers/dois.json",
        "",
    ]
    for number, paper in papers:
        doi = (dois.get(paper.slug) or {}).get("doi")
        fields = [
            f"  title       = {{{paper.title}}}",
            f"  author      = {{{' and '.join(paper.authors)}}}",
            f"  institution = {{{paper.affiliation}}}",
            f"  year        = {{{paper.year}}}",
            f"  type        = {{Technical Report}}",
            f"  number      = {{WP {number:02d}}}",
        ]
        if paper.topic:
            fields.append(f"  keywords    = {{{paper.topic}}}")
        if doi:
            fields.append(f"  doi         = {{{doi}}}")
        fields.append(f"  url         = {{{paper.url}}}")
        fields.append(f"  note        = {{Version {paper.version or '-'}, {paper.status}}}")
        blocks.append(
            f"@techreport{{{bib_key(paper)},\n" + ",\n".join(fields) + "\n}\n"
        )
    return "\n".join(blocks)


def render_cff(papers: list[tuple[int, Paper]], dois: dict) -> str:
    reference_lines = []
    for number, paper in papers:
        doi = (dois.get(paper.slug) or {}).get("doi")
        reference_lines.extend(
            [
                "  - type: report",
                f"    title: {json.dumps(paper.title, ensure_ascii=False)}",
                "    authors:",
            ]
        )
        for author in paper.authors:
            family, given = split_name(author)
            reference_lines.append("      - family-names: " + json.dumps(family, ensure_ascii=False))
            if given:
                reference_lines.append("        given-names: " + json.dumps(given, ensure_ascii=False))
        reference_lines.append(f"    year: {paper.year}")
        reference_lines.append(f"    date-published: {paper.date}")
        reference_lines.append(f"    number: \"WP {number:02d}\"")
        reference_lines.append(f"    url: {paper.url}")
        if doi:
            reference_lines.append(f"    doi: {doi}")
        reference_lines.append(
            f"    notes: {json.dumps(paper.status + ' · ' + paper.license, ensure_ascii=False)}"
        )

    header = [
        "cff-version: 1.2.0",
        f"title: {json.dumps(PROJECT_TITLE)}",
        "message: If you use these whitepapers, please cite them as shown below.",
        "type: collection",
        "authors:",
        "  - family-names: Jiménez Gómez",
        "    given-names: Francisco Javier",
        "    affiliation: Brisecom SL / LAIA Project",
        f"repository-code: \"https://github.com/javi-jimenez/laia\"",
        f"url: \"https://laia.brisecom.org/\"",
        f"license: CC-BY-NC-SA-4.0",
        "references:",
    ]
    return "\n".join(header + reference_lines) + "\n"


def render_json(papers: list[tuple[int, Paper]], dois: dict) -> str:
    payload = {
        "generatedBy": "scripts/whitepaper_citations.py",
        "source": "https://github.com/javi-jimenez/laia/tree/main/whitepapers",
        "papers": [],
    }
    for number, paper in papers:
        entry = dois.get(paper.slug) or {}
        payload["papers"].append(
            {
                "order": number,
                "slug": paper.slug,
                "citationId": paper.citation_id,
                "title": paper.title,
                "authors": list(paper.authors),
                "affiliation": paper.affiliation,
                "date": paper.date,
                "year": paper.year,
                "version": paper.version,
                "status": paper.status,
                "license": paper.license,
                "topic": paper.topic,
                "keywords": list(paper.keywords),
                "url": paper.url,
                "pdfUrl": paper.pdf_url,
                "doi": entry.get("doi"),
                "zenodoRecord": entry.get("zenodoRecord"),
            }
        )
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate CITATION.cff, references.bib and metadata.json."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if any artifact is out of date",
    )
    args = parser.parse_args()

    papers = numbered(load_papers())
    dois = load_dois()

    outputs = {
        CFF_FILE: render_cff(papers, dois),
        BIB_FILE: render_bibtex(papers, dois),
        JSON_FILE: render_json(papers, dois),
    }

    stale: list[str] = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(str(path.relative_to(REPO_ROOT)))
        if not args.check:
            path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("Citation metadata is out of date: " + ", ".join(stale))
            print("Run: make citations")
            return 1
        print(f"Citation metadata is up to date ({len(papers)} documents).")
        return 0

    if stale:
        print("Updated " + ", ".join(stale))
    else:
        print(f"Citation metadata already up to date ({len(papers)} documents).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
